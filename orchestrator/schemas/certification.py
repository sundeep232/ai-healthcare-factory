"""M5 Certify / M6 Publish contracts.

A Certification is the evidence that a *live* demo does what its blueprint promised.
A Manifest is the public, secret-free snapshot published behind a share link.
"""

from __future__ import annotations

from datetime import date as date_type
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field, computed_field


def _now() -> datetime:
    return datetime.now(timezone.utc)


class CheckStatus(str, Enum):
    PASS = "pass"
    WARN = "warn"  # worth knowing, does not block publishing
    FAIL = "fail"  # blocks certification
    SKIP = "skip"  # not applicable to this blueprint


class CheckCategory(str, Enum):
    DEPLOYMENT = "deployment"
    DATA = "data"
    SECURITY = "security"


class CheckResult(BaseModel):
    """One verifiable statement about the live instance.

    ``summary`` and ``evidence`` are published on the share page, so they only ever hold
    counts, table names and our own wording. ``detail`` is owner-only diagnostics (it may
    quote an error message) and is never published.
    """

    id: str = Field(description="Stable identifier, e.g. 'data.claim.ref.member_id'.")
    category: CheckCategory
    title: str
    status: CheckStatus
    summary: str = Field("", description="Public-safe one-line result.")
    detail: str = Field("", description="Owner-only diagnostics.")
    evidence: dict[str, Any] = Field(default_factory=dict, description="Public-safe numbers.")


class Certification(BaseModel):
    """Outcome of one M5 run."""

    checks: list[CheckResult]
    blueprint_version: int
    data_seed: int | None = Field(None, description="Seed of the data this run verified.")
    certified_at: datetime = Field(default_factory=_now)

    def _count(self, status: CheckStatus) -> int:
        return sum(1 for c in self.checks if c.status == status)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def passed(self) -> bool:
        """Certified = nothing failed and at least one real check passed."""
        return self._count(CheckStatus.FAIL) == 0 and self._count(CheckStatus.PASS) > 0

    @computed_field  # type: ignore[prop-decorator]
    @property
    def summary(self) -> dict[str, int]:
        return {s.value: self._count(s) for s in CheckStatus}


class Publication(BaseModel):
    """A live share link. The token is the capability: anyone holding it can read the manifest."""

    token: str
    published_at: datetime = Field(default_factory=_now)
    share_path: str = Field(description="Relative path of the share page, e.g. /share/<token>.")
    share_url: str = Field(description="Absolute URL when PUBLIC_BASE_URL is configured, else the path.")


class ManifestResource(BaseModel):
    id: str
    type: str
    name: str
    purpose: str
    sku: str | None = None


class ManifestTable(BaseModel):
    name: str
    rows: int


class ManifestEndpoint(BaseModel):
    name: str
    url: str


class ManifestCheck(BaseModel):
    """A check as published: the owner-only ``detail`` is deliberately absent."""

    id: str
    category: CheckCategory
    title: str
    status: CheckStatus
    summary: str
    evidence: dict[str, Any] = Field(default_factory=dict)


class ManifestCertification(BaseModel):
    passed: bool
    certified_at: datetime
    summary: dict[str, int]
    checks: list[ManifestCheck]


class Manifest(BaseModel):
    """Everything a stakeholder may see about a published demo. Built from an allow-list."""

    demo_id: str
    demo_name: str
    summary: str
    intent: str
    target_audience: str
    business_goals: list[str]
    region: str
    blueprint_version: int
    resources: list[ManifestResource]
    endpoints: list[ManifestEndpoint]
    data_as_of: date_type | None = None
    data_seed: int | None = None
    domains: list[str]
    tables: list[ManifestTable]
    certification: ManifestCertification
    published_at: datetime = Field(default_factory=_now)
    synthetic_data_notice: str = (
        "All data in this demo is synthetic. It was generated by a program, contains no real "
        "people, and cannot be traced to any real person or organization."
    )
